/** 模型可能写 "IconSun" / "sun" / "Sun" / "cloud_rain"，都认。 */
export function iconFor(name: unknown): TablerIcon | null {
  if (typeof name !== "string" || !name.trim()) return null;
  const key = name
    .trim()
    .replace(/^icon[-_ ]?/i, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();
  const aliases: Record<string, string> = {
    github: "brand-github",
    bitcoin: "currency-bitcoin",
    btc: "currency-bitcoin",
    dollar: "currency-dollar",
    yuan: "currency-yuan",
    rain: "cloud-rain",
    storm: "cloud-storm",
    alert: "alert-triangle",
    warning: "alert-triangle",
    info: "info-circle",
    ok: "circle-check",
    error: "circle-x",
    fork: "git-fork",
    commit: "git-commit",
    time: "clock",
    date: "calendar",
    location: "map-pin",
    weather: "cloud",
    stock: "chart-line",
    news: "news",
    fire: "flame",
  };
  return (
    (RICH_ICONS as Record<string, TablerIcon>)[key] ??
    (RICH_ICONS as Record<string, TablerIcon>)[aliases[key] ?? ""] ??
    null
  );
}
