/**
 * Route authorization registry — the single list every HTTP route the server can register must
 * appear in. Maintained by hand; enforced by server/tests/route-auth-inventory.test.ts, which
 * enumerates the real Hono route table and fails on anything missing here.
 *
 * Classes:
 * - public: reachable without sign-in (health, version, OAuth callbacks, public pages).
 * - user: any signed-in person; the handler scopes data by actor.id itself.
 * - admin: requireAdmin or an equivalent administrator check.
 * - machine: authenticated by a non-session credential (device token, signed webhook, bearer).
 * - middleware: a use() mount entry in the route table, not an endpoint; registration only.
 *
 * verify:false means the classification is registered but cannot be behavior-probed without a
 * database; the reason says where the check is verified in code instead.
 */
