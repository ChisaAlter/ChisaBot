/**
 * The lines a Bot hands a person asking "how do I connect this", by pathway kind.
 *
 * Written as instructions rather than a status report, because that is what the
 * tool exists to produce — the same text `connect_service` composes and the
 * directory page paraphrases. One line per step/option, prefixed by the caller.
 */
export function pathwayLines(entry: DirectoryEntry): readonly string[] {
  switch (entry.connect.kind) {
    case "remote":
      return entry.catalogueKey
        ? [
            `官方 remote MCP，已收录进本部署的连接器目录——管理员在 设置 → 插件 → 探索插件 里一键添加${entry.connect.auth !== "无需凭证" ? `并粘贴凭据（${entry.connect.auth}）` : ""}；也可以直接说「开启 ${entry.title.replace(/（.*）/u, "")}」。`,
          ]
        : [
            `官方/托管 remote MCP 端点：${entry.connect.url}（${entry.connect.auth}）。`,
            "管理员可在 设置 → 插件 → 添加自定义 MCP 填入该地址；若地址本身携带凭证参数或需 OAuth/个人 token，先看备注——本部署可能暂不支持该凭据形态。",
          ];
    case "stdio":
      return [
        `${entry.official ? "官方" : "社区"} stdio MCP 包。两条路：`,
        `1) 你已配对的电脑——我可以直接调 device_mcp_call 在你电脑上拉起${entry.connect.command ? ` \`${entry.connect.command}\`` : "（命令按仓库 README，通常是 npx/uvx）"}${entry.connect.env?.length ? `，需要环境变量 ${entry.connect.env.join("、")}` : ""}；先在 设置 → 设备 配对并允许「命令行」能力。`,
        `2) 你自己的客户端——把仓库里的 MCP 配置加进 Cherry Studio / Cursor / Claude Desktop。仓库：${entry.connect.repoUrl ?? entry.docsUrl}`,
      ];
    case "link":
      return [
        `该服务目前没有可用 MCP Server（官方提供的是 API / Skill / 托管市场）。文档入口：${entry.docsUrl}。`,
        "需要它时可以让我联网查接入细节；等官方出了 MCP 再从目录添加。",
      ];
  }
}
