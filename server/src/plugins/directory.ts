/**
 * The China-app connection directory — the whole awesome-china-mcp index (CC0),
 * as browsable data rather than as admissible connectors.
 *
 * WHY A SEPARATE FILE FROM `catalogue.ts`. The catalogue is a reviewed source
 * contract: every host in it is one this deployment may hand a credential to,
 * and the list is deliberately short. This directory is the superset — every
 * service a person might ask about, with an honest answer about HOW to reach
 * it rather than a blanket "unavailable". Promotion is one-directional: an
 * entry here earns a catalogue row only when the vendor publishes an official
 * remote MCP endpoint over Streamable HTTP with a credential model this
 * deployment honours, and `catalogueKey` on the entry marks which ones did.
 *
 * `connect` describes the pathway, so the answer is never "no":
 *
 * - `remote` — a hosted endpoint exists. When `catalogueKey` is set the admin
 *   adds it in one click from its own page; otherwise the address is for the
 *   custom-MCP dialog, and `auth` says why it may still not fit (query-string
 *   keys this build cannot place, OAuth, a personal token, a login session).
 * - `stdio` — an npm/uvx/GitHub package. The pathway is the paired-PC bridge:
 *   `device_mcp_call` runs the command on the person's own computer, which is
 *   also where community servers that hold account sessions belong — the
 *   session stays on the person's machine and the deployment stores nothing.
 * - `link` — official API / Agent Skill / hosted marketplace / registry. No
 *   MCP server to connect; `docsUrl` is the pathway itself.
 */

