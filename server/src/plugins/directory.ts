export type DirectoryConnect =
  | { kind: "remote"; url: string; auth: string }
  | {
      kind: "stdio";
      command?: string;
      repoUrl?: string;
      env?: readonly string[];
    }
  | { kind: "link" };

export type DirectoryEntry = {
  /** Stable slug, unique across the whole directory. */
  key: string;
  title: string;
  vendor: string;
  category: DirectoryCategory;
  /** One line of zh — what the service can do for a Bot. */
  summary: string;
  /** 官方 first-party vs 社区 community, as the source list tags them. */
  official: boolean;
  connect: DirectoryConnect;
  /** Set when the reviewed catalogue already carries this service — the one-click path. */
  catalogueKey?: string;
  /** A warning or caveat the connect dialog must not drop (session risk, billing, gaps). */
  note?: string;
  docsUrl: string;
};

const remote = (url: string, auth: string): DirectoryConnect => ({
  kind: "remote",
  url,
  auth,
});
const stdio = (
  repoUrl: string,
  command?: string,
  env?: readonly string[],
): DirectoryConnect => ({ kind: "stdio", repoUrl, command, env });
const link: DirectoryConnect = { kind: "link" };

